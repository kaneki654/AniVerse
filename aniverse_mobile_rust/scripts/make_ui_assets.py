#!/usr/bin/env python3
"""Build the two generated inputs of the Slint UI from the Flutter app's own sources.

1. ui/icons.slint: the Material icons the manga UI draws (InkIcons in
   aniverse_mobile/lib/ui_manga/ink/manga.dart), as SVG path strings taken from
   Flutter's MaterialIcons-Regular.otf, so the Rust app shows the same glyphs.
2. assets/fonts/manga/MangaTitle-Oblique.ttf: Lato Black slanted the way
   Flutter fakes italics (a 1/4 skew), because MgFont.heading asks for italic
   and the bundled Lato Black has no italic face. Renamed "MangaTitle": Lato's
   licence reserves its name for unmodified fonts.

Run with the repository's venv (it has fontTools), from aniverse_mobile_rust:
    /home/kaneki/AniVerse/venv/bin/python scripts/make_ui_assets.py
"""
from __future__ import annotations

import pathlib
import sys

from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parents[1]
MATERIAL = pathlib.Path.home() / "flutter/bin/cache/artifacts/material_fonts/MaterialIcons-Regular.otf"

# InkIcons name -> Material codepoint (the same table as app/static/manga/js/icons.js,
# generated from the glyphs the app uses), plus the player's extra controls.
ICONS = {
    "play": 0xF00A0, "pause": 0xF0056, "back": 0xF572, "chevron": 0xF63B,
    "rewind": 0xF735, "forward": 0xF734, "skip-next": 0xF0192, "search": 0xF013D,
    "gear": 0xF0164, "user": 0xF0071, "grid": 0xF7C4, "list": 0xF0281,
    "clock": 0xF012B, "trash": 0xF697, "fullscreen": 0xF7A6, "fullscreen-exit": 0xF7A5,
    "swap": 0xF01FA, "refresh": 0xF00E9, "check": 0xF636, "close": 0xF647,
    "eye": 0xF0293, "eye-off": 0xF0292, "lock": 0xF889, "logout": 0xF88B,
    "floppy": 0xF0126, "star": 0xF01D4, "blood-drop": 0xF03B4, "skull": 0xF0151,
    "skull-small": 0xF014D, "volume": 0xF029A, "mute": 0xF0299, "download": 0xF6DF,
    "home": 0xF7F5, "calendar": 0xF06C8, "bookmark": 0xF5D1, "bookmark-off": 0xF5CF,
    "bell": 0xF002A, "trophy": 0xF707, "flag": 0xF768, "party": 0xF7C8,
    "sword": 0xF5CA, "pip": 0xF0097, "gauge": 0xF01B5, "share": 0xF016A,
    "cast": 0xF622, "subtitles": 0xF01EF,
}


def icon_paths() -> dict[str, str]:
    font = TTFont(MATERIAL)
    upm = font["head"].unitsPerEm
    ascent = font["hhea"].ascent
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    out = {}
    for name, code in ICONS.items():
        glyph = cmap.get(code)
        if glyph is None:
            sys.exit(f"MaterialIcons has no glyph for {name} (U+{code:X})")
        pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
        # Font units grow upward; Slint paths, like SVG, grow downward.
        glyphs[glyph].draw(TransformPen(pen, (1, 0, 0, -1, 0, ascent)))
        out[name] = pen.getCommands()
    assert upm == 512, upm
    return out


def write_icons() -> None:
    paths = icon_paths()
    lines = [
        "// Generated by scripts/make_ui_assets.py from Flutter's MaterialIcons-Regular.otf:",
        "// the same rounded glyphs as InkIcons in lib/ui_manga/ink/manga.dart (512-unit box).",
        "export global Icons {",
    ]
    for name, d in paths.items():
        lines.append(f'    out property <string> {name}: "{d}";')
    lines.append("}")
    (ROOT / "ui/icons.slint").write_text("\n".join(lines) + "\n")
    print(f"ui/icons.slint: {len(paths)} icons")


PLAYER_GLYPHS = ["back", "play", "pause", "rewind", "forward", "skip-next", "pip", "fullscreen",
                 "fullscreen-exit", "gear", "swap", "refresh"]


def write_kotlin_glyphs() -> None:
    """The player overlay's buttons draw the same glyphs (androidx PathParser)."""
    paths = icon_paths()
    lines = [
        "package app.aniverse.rust",
        "",
        "// Generated by scripts/make_ui_assets.py from Flutter's MaterialIcons-Regular.otf:",
        "// the player's button glyphs, as SVG path data in a 512-unit box.",
        "object Glyphs {",
    ]
    for name in PLAYER_GLYPHS:
        const = name.upper().replace("-", "_")
        lines.append(f'    const val {const} = "{paths[name]}"')
    lines.append("}")
    out = ROOT / "android/app/src/main/java/app/aniverse/rust/Glyphs.kt"
    out.write_text("\n".join(lines) + "\n")
    print(f"{out.relative_to(ROOT)}: {len(PLAYER_GLYPHS)} glyphs")


def write_oblique_title(family: str = "MangaTitle", skew: float = 0.25) -> None:
    """[skew] 0.25 is Skia's fake italic (setSkewX(-1/4) in y-down space).
    Section headers sit in a box skewed by Matrix4.skewX(-0.12) as well, which
    leans their lettering further: tan(0.12) on top of the 1/4."""
    src = ROOT / "assets/fonts/manga/Lato-Black.ttf"
    font = TTFont(src)
    glyphs = font.getGlyphSet()
    order = font.getGlyphOrder()
    drawn = {}
    for name in order:
        rec = DecomposingRecordingPen(glyphs)
        glyphs[name].draw(rec)
        tt = TTGlyphPen(None)
        rec.replay(TransformPen(tt, (1, 0, skew, 1, 0, 0)))
        drawn[name] = tt.glyph()
    glyf = font["glyf"]
    for name, g in drawn.items():
        glyf[name] = g
    # Hinting was written for the upright outlines.
    for table in ("fpgm", "prep", "cvt ", "hdmx", "LTSH", "VDMX"):
        if table in font:
            del font[table]
    hmtx = font["hmtx"]
    for name in order:
        g = glyf[name]
        g.recalcBounds(glyf)
        advance, _ = hmtx[name]
        hmtx[name] = (advance, getattr(g, "xMin", 0))
    font["post"].italicAngle = -14.0
    names = font["name"]
    for record in list(names.names):
        if record.nameID in (1, 4, 16):
            names.setName(family, record.nameID, record.platformID, record.platEncID, record.langID)
        elif record.nameID in (2, 17):
            names.setName("Regular", record.nameID, record.platformID, record.platEncID, record.langID)
        elif record.nameID == 6:
            names.setName(f"{family}-Regular", record.nameID, record.platformID, record.platEncID, record.langID)
        elif record.nameID == 3:
            names.setName(f"{family}-Regular;AniVerse", record.nameID, record.platformID, record.platEncID, record.langID)
    out = ROOT / f"assets/fonts/manga/{family}-Oblique.ttf"
    font.save(out)
    print(f"{out.relative_to(ROOT)}: Lato Black, skewed {skew}")


if __name__ == "__main__":
    import math

    write_icons()
    write_kotlin_glyphs()
    write_oblique_title()
    write_oblique_title("MangaCaption", 0.25 + math.tan(0.12))
    # The player overlay letters with the same faces, and the manga sounds play natively.
    import shutil

    assets = ROOT / "android/app/src/main/assets/fonts"
    assets.mkdir(parents=True, exist_ok=True)
    for name in ("MangaTitle-Oblique.ttf", "RobotoCondensed-Bold.ttf"):
        shutil.copyfile(ROOT / "assets/fonts/manga" / name, assets / name)
    raw = ROOT / "android/app/src/main/res/raw"
    raw.mkdir(parents=True, exist_ok=True)
    flutter_raw = ROOT.parent / "aniverse_mobile/android/app/src/main/res/raw"
    sounds = sorted(flutter_raw.glob("manga_*.wav"))
    for wav in sounds:
        shutil.copyfile(wav, raw / wav.name)
    print(f"android assets: 2 fonts, {len(sounds)} sounds")
