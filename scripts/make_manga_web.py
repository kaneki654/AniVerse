"""Build the manga website's assets (app/static/manga) from the app's.

    venv/bin/python scripts/make_manga_web.py

- fonts/: the manga lettering as woff2 (Lato Black, Roboto Condensed, the kana
  cut of Noto Sans CJK from scripts/make_manga_assets.py) and the icons: the
  Material icon font Flutter ships, cut to the glyphs the website uses, so the
  site and the app draw the same icons. Licences alongside.
- js/icons.js: the icon names the pages use -> codepoints in that font.
- img/: the inked emblem and its layers, and the favicons and install icons
  drawn from it on paper.
- sfx/: the manga sound effects (scripts/make_manga_sfx.py renders them).

Run scripts/make_manga_assets.py and scripts/make_manga_sfx.py first.
"""

import re
import shutil
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "aniverse_mobile"
OUT = ROOT / "app" / "static" / "manga"
MATERIAL = Path.home() / "flutter" / "bin" / "cache" / "artifacts" / "material_fonts"
ICONS_DART = Path.home() / "flutter" / "packages" / "flutter" / "lib" / "src" / "material" / "icons.dart"

# The website's icon names (the pixel sprites' names) -> Material icons, the
# same choices as the app's InkIcons (lib/ui_manga/ink/manga.dart).
ICONS = {
    "play": "play_arrow_rounded", "pause": "pause_rounded", "back": "arrow_back_rounded",
    "chevron": "chevron_right_rounded", "rewind": "fast_rewind_rounded", "forward": "fast_forward_rounded",
    "skipNext": "skip_next_rounded", "search": "search_rounded", "gear": "settings_rounded",
    "user": "person_rounded", "grid": "grid_view_rounded", "list": "view_agenda_rounded",
    "clock": "schedule_rounded", "trash": "delete_rounded", "fullscreen": "fullscreen_rounded",
    "fullscreenExit": "fullscreen_exit_rounded", "swap": "swap_horiz_rounded", "refresh": "refresh_rounded",
    "check": "check_rounded", "close": "close_rounded", "eye": "visibility_rounded",
    "eyeOff": "visibility_off_rounded", "lock": "lock_rounded", "logout": "logout_rounded",
    "floppy": "save_rounded", "star": "star_rounded", "bloodDrop": "water_drop_rounded",
    "skull": "sentiment_very_dissatisfied_rounded", "skullSmall": "sentiment_dissatisfied_rounded",
    "volume": "volume_up_rounded", "mute": "volume_off_rounded", "download": "download_rounded",
    "home": "home_rounded", "calendar": "calendar_month_rounded", "bookmark": "bookmark_rounded",
    "bookmarkOff": "bookmark_border_rounded", "bell": "notifications_rounded", "trophy": "emoji_events_rounded",
    "flag": "flag_rounded", "party": "groups_rounded", "sword": "bolt_rounded", "bolt": "bolt_rounded",
    "pip": "picture_in_picture_alt_rounded", "blossom": "local_florist_rounded", "heart": "favorite_rounded",
    "torii": "temple_buddhist_rounded", "gauge": "speed_rounded", "mark": "bookmark_rounded",
    "share": "share_rounded", "cast": "cast_rounded", "subtitles": "subtitles_rounded",
}


def _woff2(src: Path, dst: Path) -> None:
    font = TTFont(src)
    font.flavor = "woff2"
    font.save(dst)


def fonts() -> None:
    d = OUT / "fonts"
    d.mkdir(parents=True, exist_ok=True)
    src = APP / "assets" / "fonts" / "manga"
    _woff2(src / "Lato-Black.ttf", d / "MangaTitle.woff2")
    _woff2(src / "RobotoCondensed-Regular.ttf", d / "MangaText-Regular.woff2")
    _woff2(src / "RobotoCondensed-Bold.ttf", d / "MangaText-Bold.woff2")
    _woff2(src / "MangaSfx-Bold.otf", d / "MangaSfx.woff2")
    for lic in src.glob("LICENSE-*.txt"):
        shutil.copy(lic, d / lic.name)
    shutil.copy(MATERIAL / "MaterialIcons_LICENSE.txt", d / "LICENSE-MaterialIcons.txt")

    # The icons: codepoints from Flutter's icons.dart, glyphs from its font.
    dart = ICONS_DART.read_text(encoding="utf-8")
    codes = {}
    for name, icon in ICONS.items():
        m = re.search(rf"static const IconData {icon} = IconData\(\s*0x([0-9a-f]+)", dart)
        if not m:
            raise SystemExit(f"no Material icon {icon}")
        codes[name] = int(m.group(1), 16)
    font = TTFont(MATERIAL / "MaterialIcons-Regular.otf")
    opts = subset.Options()
    opts.layout_features = []
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=set(codes.values()))
    sub.subset(font)
    font.flavor = "woff2"
    font.save(d / "MangaIcons.woff2")
    lines = [f"  {name}: 0x{code:x}," for name, code in codes.items()]
    (OUT / "js").mkdir(parents=True, exist_ok=True)
    (OUT / "js" / "icons.js").write_text(
        "// Generated by scripts/make_manga_web.py: icon name -> codepoint in fonts/MangaIcons.woff2\n"
        "// (Material icons, the same glyphs the app's manga UI draws).\n"
        "export const ICONS = {\n" + "\n".join(lines) + "\n};\n", encoding="utf-8")


def images() -> None:
    d = OUT / "img"
    d.mkdir(parents=True, exist_ok=True)
    for name in ("logo.png", "logo_lines.png", "logo_tone.png", "logo_color.png"):
        shutil.copy(APP / "assets" / "manga" / name, d / name)
    emblem = Image.open(APP / "assets" / "manga" / "logo.png").convert("RGBA")
    paper = (245, 241, 232, 255)

    def icon(size: int, inset: float, name: str) -> None:
        canvas = Image.new("RGBA", (size, size), paper)
        side = int(size * (1 - 2 * inset))
        e = emblem.resize((side, side), Image.Resampling.LANCZOS)
        canvas.alpha_composite(e, (int(size * inset), int(size * inset)))
        canvas.convert("RGB").save(d / name, optimize=True)

    emblem.resize((32, 32), Image.Resampling.LANCZOS).save(d / "favicon-32.png", optimize=True)
    icon(180, 0.06, "apple-touch-icon.png")
    icon(192, 0.06, "icon-192.png")
    icon(512, 0.06, "icon-512.png")
    icon(512, 0.16, "icon-maskable-512.png")  # inside the circle a launcher may crop to


def sounds() -> None:
    d = OUT / "sfx"
    d.mkdir(parents=True, exist_ok=True)
    for wav in (APP / "android" / "app" / "src" / "main" / "res" / "raw").glob("manga_*.wav"):
        shutil.copy(wav, d / wav.name.removeprefix("manga_"))


def main() -> None:
    fonts()
    images()
    sounds()
    for p in sorted(OUT.rglob("*")):
        if p.is_file() and (p.suffix != ".js" or p.name == "icons.js"):
            print(f"{p.relative_to(ROOT)}  {p.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
